// Halving add, see reference/performance.md.
TEXT ·liftOddNEON(SB), NOSPLIT, $0-40
	MOVD out+0(FP), R0
	MOVD l+8(FP), R1
	MOVD h0+16(FP), R2
	MOVD h1+24(FP), R3
	MOVD n+32(FP), R4
oloop:
	VLD1.P 16(R1), [V0.H8]
	VLD1.P 16(R2), [V1.H8]
	VLD1.P 16(R3), [V2.H8]
	VSHADD V2.H8, V1.H8, V3.H8
	VSRSHR $1, V3.H8, V3.H8
	VSUB   V3.H8, V0.H8, V0.H8
	VST1.P [V0.H8], 16(R0)
	SUBS $8, R4
	BNE  oloop
	RET

